using System.Globalization;
using GPC.Geometry;

namespace GPC.Design.Sections;

/// <summary>A longitudinal bar of a free section: centre (<paramref name="X"/>, <paramref name="Y"/>) and <paramref name="Diameter"/> in mm,
/// in the coordinates of the drawing.</summary>
public sealed record ConcreteFreeBar(double X, double Y, double Diameter);

/// <summary>
/// A concrete section of any shape read from a drawing (DXF/DWG by the application). All lengths in mm, in the coordinates of the drawing.
/// Each polygon is a list of vertices in order, in either direction (clockwise or counterclockwise: the library normalizes it), closed by
/// the side from the last vertex to the first; the first vertex may be repeated at the end. Arcs arrive already split into segments.
/// </summary>
/// <param name="Outline">The outer boundary of the concrete: at least 3 vertices, a simple polygon.</param>
/// <param name="Holes">The holes, each strictly inside the outline and apart from the others; empty (or null) for none.</param>
/// <param name="Bars">The longitudinal bars, 1 to 2000, each wholly in the concrete.</param>
public sealed record ConcreteFreeSectionInput(IReadOnlyList<Point2d> Outline, IReadOnlyList<IReadOnlyList<Point2d>>? Holes,
    IReadOnlyList<ConcreteFreeBar> Bars);

public static partial class ConcreteSectionTemplates
{
    /// <summary>Most vertices of one polygon (outline or hole).</summary>
    public const int FreeSectionMaximumVertices = 5000;

    /// <summary>Most bars of a free section, as for the templates.</summary>
    public const int FreeSectionMaximumBars = 2000;

    /// <summary>
    /// The geometry of a free section, in the format of the templates (<see cref="Create"/>), for the same use by the application:
    /// <list type="bullet">
    /// <item>coordinates centred on the concrete centroid, as the templates; <see cref="ConcreteTemplateGeometry.InputCentroid"/> is that
    /// centroid in the coordinates of the drawing (returned point = input point − InputCentroid);</item>
    /// <item><see cref="ConcreteTemplateGeometry.Shape"/>: outline counterclockwise (positive area) and holes in the same direction, as
    /// <see cref="Shape2d"/> keeps them, each starting from its first vertex of the input; the vertices are those given, moved;</item>
    /// <item>bars in the order given, with area π Ø² / 4; no links (empty list), no column bar path;</item>
    /// <item>fibres: the same 48 × 48 sampling of the templates (stress maps only); the DelaunayMesh mesh for equilibrium is generated by
    /// GPCModel from the shape (ReinforcedConcreteSection), as for the templates;</item>
    /// <item><see cref="ConcreteTemplateGeometry.Area"/> the net area; Width and Height those of the bounding box of the outline.</item>
    /// </list>
    /// Checks, with a message in Italian for the user: polygons with at least 3 vertices, finite coordinates, no side of zero length, no
    /// self-intersection or self-contact, non-zero area; holes strictly inside the outline, not touching it, not overlapping or touching each
    /// other; positive net area; 1 to 2000 bars with finite coordinates and positive diameter, each wholly in the concrete (neither outside the
    /// outline nor in a hole nor across their sides: the rule of the application, cover ≥ −1e-8 mm) and not overlapping another bar
    /// (centre distance greater than the sum of the radii). The length tolerance is <see cref="GeometryBase.Tolerance"/> (1e-4 mm).
    /// </summary>
    /// <exception cref="ArgumentNullException">If <paramref name="input"/> is null.</exception>
    /// <exception cref="ArgumentException">If a datum is not valid, with the reason in the message; no partial geometry is returned.</exception>
    public static ConcreteTemplateGeometry CreateFree(ConcreteFreeSectionInput input)
    {
        Guard.NotNull(input);
        var outline = FreePolygon(input.Outline, "Contorno");
        var holes = new List<Point2d[]>();
        if (input.Holes is not null)
            for (int k = 0; k < input.Holes.Count; k++) holes.Add(FreePolygon(input.Holes[k], "Foro " + (k + 1)));
        CheckFreeRegion(outline, holes);
        outline = Counterclockwise(outline, "Contorno");
        for (int k = 0; k < holes.Count; k++) holes[k] = Counterclockwise(holes[k], "Foro " + (k + 1));
        double perimeter = Perimeter(outline) + holes.Sum(Perimeter);

        var shape = Centred(new Shape2d(new Polygon2d(outline), holes.Select(h => new Polygon2d(h)).ToArray()), out double area, out var center);
        if (!PortableMath.IsFinite(area) || area <= GeometryBase.Tolerance * perimeter)
            throw new ArgumentException("Area netta della sezione nulla o negativa: i fori occupano tutto il calcestruzzo.");
        var bars = FreeBars(input.Bars, shape, center);
        var fibers = SampleFibers(shape, out double width, out double height);
        return new(shape, bars, Array.Empty<ConcreteTemplateLink>(), fibers, width, height, area,
            "Sezione di forma libera: nessuna staffa generata. Per il taglio assegnare esplicitamente bw, d, Asl e i bracci efficaci per direzione; " +
            "la torsione richiede un modello dedicato.")
        { InputCentroid = center };
    }

    private static string Mm(double value) => value.ToString("0.###", CultureInfo.InvariantCulture);

    /// <summary>The vertices copied in the order of the input, without the repeated closing vertex.</summary>
    private static Point2d[] FreePolygon(IReadOnlyList<Point2d>? source, string name)
    {
        if (source is null) throw new ArgumentException(name + ": vertici mancanti.");
        var points = new List<Point2d>(source.Count);
        for (int i = 0; i < source.Count; i++)
        {
            var p = source[i] ?? throw new ArgumentException($"{name}: manca il vertice {i + 1}.");
            if (!PortableMath.IsFinite(p.X) || !PortableMath.IsFinite(p.Y))
                throw new ArgumentException($"{name}: coordinate non finite al vertice {i + 1}.");
            points.Add(new Point2d(p.X, p.Y));
        }
        // A closed polyline may repeat its first vertex at the end: that is the closing side, not a side of zero length.
        if (points.Count > 1 && points[0].DistanceTo(points[points.Count - 1]) <= GeometryBase.Tolerance) points.RemoveAt(points.Count - 1);
        if (points.Count < 3) throw new ArgumentException($"{name}: servono almeno 3 vertici distinti (ne sono dati {points.Count}).");
        if (points.Count > FreeSectionMaximumVertices)
            throw new ArgumentException($"{name}: {points.Count} vertici, al massimo {FreeSectionMaximumVertices}: suddividere gli archi in meno tratti.");
        for (int i = 0; i < points.Count; i++)
        {
            int j = (i + 1) % points.Count;
            if (points[i].DistanceTo(points[j]) <= GeometryBase.Tolerance)
                throw new ArgumentException($"{name}: il lato fra i vertici {i + 1} e {j + 1} ha lunghezza nulla (vertici coincidenti).");
        }
        // All the vertices on one line: no area. Checked before the crossings, which would report the sides that run back on each other.
        var far = points.OrderByDescending(p => p.DistanceTo(points[0])).First();
        if (points.All(p => PointLineDistance(p, points[0], far) <= GeometryBase.Tolerance))
            throw new ArgumentException($"{name}: area nulla (vertici allineati).");
        return points.ToArray();
    }

    /// <summary>A simple polygon counterclockwise (positive area), keeping its first vertex.</summary>
    private static Point2d[] Counterclockwise(Point2d[] points, string name)
    {
        double signedArea = new Polygon2d(points).GetSignedArea();
        if (!PortableMath.IsFinite(signedArea) || Math.Abs(signedArea) <= GeometryBase.Tolerance * Perimeter(points))
            throw new ArgumentException($"{name}: area nulla.");
        if (signedArea < 0) Array.Reverse(points, 1, points.Length - 1);
        return points;
    }

    private static double PointLineDistance(Point2d p, Point2d a, Point2d b)
        => Math.Abs(Cross(a, b, p)) / PortableMath.Hypot(b.X - a.X, b.Y - a.Y);

    private static double Perimeter(Point2d[] points)
    {
        double length = 0;
        for (int i = 0; i < points.Length; i++) length += points[i].DistanceTo(points[(i + 1) % points.Length]);
        return length;
    }

    private readonly struct FreeEdge
    {
        internal FreeEdge(int polygon, int index, Point2d a, Point2d b)
        {
            Polygon = polygon; Index = index; A = a; B = b;
            XMin = Math.Min(a.X, b.X); XMax = Math.Max(a.X, b.X); YMin = Math.Min(a.Y, b.Y); YMax = Math.Max(a.Y, b.Y);
        }
        internal int Polygon { get; }
        internal int Index { get; }
        internal Point2d A { get; }
        internal Point2d B { get; }
        internal double XMin { get; }
        internal double XMax { get; }
        internal double YMin { get; }
        internal double YMax { get; }
    }

    /// <summary>Polygon 0 is the outline, k ≥ 1 the hole k. Sides are numbered from 1: side i goes from vertex i to vertex i + 1.</summary>
    private static void CheckFreeRegion(Point2d[] outline, IReadOnlyList<Point2d[]> holes)
    {
        var polygons = new List<Point2d[]> { outline };
        polygons.AddRange(holes);
        string Name(int k) => k == 0 ? "Contorno" : "Foro " + k;
        const double tolerance = GeometryBase.Tolerance;
        // Consecutive sides share only their common vertex: the far end of either one must not lie on the other (a side running back).
        // Checked first, so that such a polygon is not reported through the contact of the following side.
        for (int k = 0; k < polygons.Count; k++)
        {
            var v = polygons[k]; int count = v.Length;
            for (int i = 0; i < count; i++)
            {
                Point2d u = v[i], shared = v[(i + 1) % count], w = v[(i + 2) % count];
                if (PointSegmentDistance(w, u, shared) <= tolerance || PointSegmentDistance(u, shared, w) <= tolerance)
                {
                    int a = i + 1, b = (i + 1) % count + 1;
                    throw new ArgumentException($"{Name(k)}: i lati {Math.Min(a, b)} e {Math.Max(a, b)} si sovrappongono (il contorno torna su sé stesso).");
                }
            }
        }
        var edges = new List<FreeEdge>();
        for (int k = 0; k < polygons.Count; k++)
            for (int i = 0; i < polygons[k].Length; i++) edges.Add(new(k, i, polygons[k][i], polygons[k][(i + 1) % polygons[k].Length]));
        // Sweep on x: only the sides whose boxes overlap within the tolerance are compared.
        edges.Sort((e, f) => e.XMin != f.XMin ? e.XMin.CompareTo(f.XMin) : e.Polygon != f.Polygon ? e.Polygon.CompareTo(f.Polygon) : e.Index.CompareTo(f.Index));
        for (int s = 0; s < edges.Count; s++)
        {
            var e = edges[s];
            for (int t = s + 1; t < edges.Count && edges[t].XMin <= e.XMax + tolerance; t++)
            {
                var f = edges[t];
                if (f.YMin > e.YMax + tolerance || e.YMin > f.YMax + tolerance) continue;
                if (e.Polygon == f.Polygon)
                {
                    int count = polygons[e.Polygon].Length;
                    int first = Math.Min(e.Index, f.Index), second = Math.Max(e.Index, f.Index);
                    bool adjacent = second == first + 1 || first == 0 && second == count - 1;
                    if (!adjacent && SegmentDistance(e.A, e.B, f.A, f.B) <= tolerance)
                        throw new ArgumentException($"{Name(e.Polygon)} autointersecante: i lati {first + 1} e {second + 1} si incrociano o si toccano.");
                }
                else if (SegmentDistance(e.A, e.B, f.A, f.B) <= tolerance)
                {
                    int a = Math.Min(e.Polygon, f.Polygon), b = Math.Max(e.Polygon, f.Polygon);
                    throw new ArgumentException(a == 0 ? $"Il foro {b} tocca o attraversa il contorno della sezione."
                        : $"I fori {a} e {b} si toccano o si sovrappongono.");
                }
            }
        }
        // No side crosses or touches another: each hole is wholly inside or wholly outside the outline and the other holes.
        var outer = new Polygon2d(outline);
        for (int k = 1; k < polygons.Count; k++)
            if (!outer.IsPointInside(polygons[k][0], 0)) throw new ArgumentException($"Il foro {k} è esterno al contorno della sezione.");
        for (int a = 1; a < polygons.Count; a++)
            for (int b = a + 1; b < polygons.Count; b++)
                if (new Polygon2d(polygons[a]).IsPointInside(polygons[b][0], 0) || new Polygon2d(polygons[b]).IsPointInside(polygons[a][0], 0))
                    throw new ArgumentException($"I fori {a} e {b} si sovrappongono: uno contiene l'altro.");
    }

    private static double Cross(Point2d o, Point2d p, Point2d q) => (p.X - o.X) * (q.Y - o.Y) - (p.Y - o.Y) * (q.X - o.X);

    private static double PointSegmentDistance(Point2d p, Point2d a, Point2d b)
    {
        double ex = b.X - a.X, ey = b.Y - a.Y, length = ex * ex + ey * ey;
        double t = length > 0 ? ((p.X - a.X) * ex + (p.Y - a.Y) * ey) / length : 0;
        t = t < 0 ? 0 : t > 1 ? 1 : t;
        return PortableMath.Hypot(p.X - (a.X + t * ex), p.Y - (a.Y + t * ey));
    }

    /// <summary>Distance between the segments AB and CD: zero when they cross.</summary>
    private static double SegmentDistance(Point2d a, Point2d b, Point2d c, Point2d d)
    {
        double d1 = Cross(c, d, a), d2 = Cross(c, d, b), d3 = Cross(a, b, c), d4 = Cross(a, b, d);
        if ((d1 > 0 && d2 < 0 || d1 < 0 && d2 > 0) && (d3 > 0 && d4 < 0 || d3 < 0 && d4 > 0)) return 0;
        return Math.Min(Math.Min(PointSegmentDistance(a, c, d), PointSegmentDistance(b, c, d)),
            Math.Min(PointSegmentDistance(c, a, b), PointSegmentDistance(d, a, b)));
    }

    /// <summary>The bars moved to the centroid. Checked on the returned coordinates with the rules of the application on the same data.</summary>
    private static IReadOnlyList<DesignBar> FreeBars(IReadOnlyList<ConcreteFreeBar>? source, Shape2d shape, Point2d center)
    {
        if (source is null || source.Count == 0) throw new ArgumentException("Inserire almeno una barra.");
        if (source.Count > FreeSectionMaximumBars) throw new ArgumentException($"{source.Count} barre: al massimo {FreeSectionMaximumBars}.");
        var outer = shape.Fill2d;
        var holes = shape.Holes2d ?? [];
        var bars = new List<DesignBar>(source.Count);
        for (int i = 0; i < source.Count; i++)
        {
            var bar = source[i] ?? throw new ArgumentException($"Barra {i + 1}: dati mancanti.");
            if (!PortableMath.IsFinite(bar.X) || !PortableMath.IsFinite(bar.Y)) throw new ArgumentException($"Barra {i + 1}: coordinate non finite.");
            if (!PortableMath.IsFinite(bar.Diameter) || bar.Diameter <= 0)
                throw new ArgumentException($"Barra {i + 1}: il diametro deve essere positivo e finito (Ø = {Mm(bar.Diameter)} mm).");
            string where = $"La barra {i + 1} (x = {Mm(bar.X)}, y = {Mm(bar.Y)} mm, Ø {Mm(bar.Diameter)})";
            var position = new Point2d(bar.X - center.X, bar.Y - center.Y);
            if (!outer.IsPointInside(position, 0)) throw new ArgumentException(where + " è fuori dal contorno della sezione.");
            for (int k = 0; k < holes.Length; k++)
                if (holes[k].IsPointInside(position, 0)) throw new ArgumentException($"{where} cade nel foro {k + 1}.");
            double clearance = outer.DistanceTo(position); int nearest = 0;
            for (int k = 0; k < holes.Length; k++)
            {
                double distance = holes[k].DistanceTo(position);
                if (distance < clearance) { clearance = distance; nearest = k + 1; }
            }
            if (clearance - bar.Diameter / 2 < -1e-8)
                throw new ArgumentException(where + (nearest == 0 ? " interseca il contorno della sezione." : $" interseca il foro {nearest}."));
            for (int j = 0; j < bars.Count; j++)
                if (PortableMath.Hypot(position.X - bars[j].X, position.Y - bars[j].Y) <= (bar.Diameter + bars[j].Diameter) / 2)
                    throw new ArgumentException($"Le barre {j + 1} e {i + 1} si sovrappongono.");
            bars.Add(new(position.X, position.Y, bar.Diameter, Math.PI * bar.Diameter * bar.Diameter / 4));
        }
        return bars.AsReadOnly();
    }
}
