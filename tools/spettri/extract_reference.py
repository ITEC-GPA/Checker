"""Extract public CSLP data and compile the fixed grid-selection expressions to C#.

The generated code has no runtime spreadsheet parser, Excel dependency or editable formulas.
The cell references retain an audit trail to D1b of Spettri-NTC 1.0.3.
Run against an Excel-converted, macro-free analysis copy. Never overwrites test expected values.
"""
import argparse, csv, gzip, hashlib, io, json, re
from pathlib import Path
import openpyxl
from openpyxl.formula import Tokenizer
from openpyxl.utils.cell import range_boundaries, get_column_letter

p=argparse.ArgumentParser()
p.add_argument('workbook',type=Path)
p.add_argument('cached_data',type=Path)
p.add_argument('output',type=Path)
a=p.parse_args()
a.output.mkdir(parents=True,exist_ok=True)
w=openpyxl.load_workbook(a.workbook,read_only=True)
cells={c.coordinate:c.value for row in w['D1b'].iter_rows(max_row=84,max_col=48) for c in row if c.value is not None}
overrides={'AC2':'N(longitude)', 'AD2':'N(latitude)'}
for row in range(29,33): overrides[f'AB{row}']=f'N(Nearest(G("AC{row-6}").Number, G("AD{row-6}").Number))'
for row in range(30,34): overrides[f'AI{row}']=f'Truth(Eq(G("AN29"), N(0))) ? G("AI29") : N(Nearest(G("AJ{row-7}").Number, G("AK{row-7}").Number))'
overrides['AI41']='N(Nearest(G("AJ37").Number, G("AK37").Number))'
needed=set()

def dependencies(ref):
    x1,y1,x2,y2=range_boundaries(ref)
    return [get_column_letter(c)+str(r) for r in range(y1,y2+1) for c in range(x1,x2+1)]

class Parser:
    def __init__(self,formula):
        self.t=[t for t in Tokenizer(formula).items if t.type!='WHITE-SPACE']; self.i=0
    def expr(self,minimum=0):
        t=self.t[self.i]; self.i+=1
        if t.type=='OPERATOR-PREFIX': left='('+t.value+self.expr(5)+')'
        elif t.type=='PAREN' and t.subtype=='OPEN':
            left=self.expr(); self.i+=1
        elif t.type=='FUNC' and t.subtype=='OPEN':
            name=t.value[:-1]; args=[]
            if self.t[self.i].subtype!='CLOSE':
                while True:
                    args.append(self.expr())
                    if self.t[self.i].type!='SEP': break
                    self.i+=1
            self.i+=1
            if name=='IF': left=f'(Truth({args[0]}) ? {args[1]} : {args[2]})'
            elif name=='PI': left='N(Math.PI)'
            else: left={'ABS':'Abs','SQRT':'Sqrt','SIN':'Sin','COS':'Cos','TAN':'Tan','ATAN':'Atan','ASINH':'Asinh','MIN':'Min','MAX':'Max','SUM':'Sum','AND':'And','OR':'Or','INDEX':'Index','VLOOKUP':'Lookup'}[name]+'('+', '.join(args)+')'
        elif t.subtype=='NUMBER': left='N('+t.value+')'
        elif t.subtype=='TEXT': left='S('+json.dumps(t.value[1:-1].replace('""','"'))+')'
        elif t.subtype=='LOGICAL': left='B('+t.value.lower()+')'
        elif t.subtype=='RANGE':
            ref=t.value.replace('$','')
            if ref in ['G5:G10755','H5:H10755']: left='node'+('X' if ref.startswith('G') else 'Y')
            elif ':' in ref:
                needed.update(dependencies(ref)); left='R("'+ref+'")'
            else: needed.add(ref); left='G("'+ref+'")'
        else: raise ValueError(t)
        while self.i<len(self.t) and self.t[self.i].type=='OPERATOR-INFIX':
            op=self.t[self.i].value; power={'=':1,'<>':1,'<':1,'>':1,'<=':1,'>=':1,'+':2,'-':2,'*':3,'/':3,'^':4}[op]
            if power<minimum: break
            self.i+=1; right=self.expr(power+1)
            if op in ['+','-','*','/']: left=f'({left} {op} {right})'
            else: left={'=':'Eq','<>':'Ne','<':'Lt','>':'Gt','<=':'Le','>=':'Ge','^':'Pow'}[op]+f'({left}, {right})'
        return left

roots=['AC3','AD3','AC51','AG79','AH2']+[f'{col}{r}' for col,rows in [('AF',range(81,85)),('AH',range(3,7)),('AH',range(9,13))] for r in rows]
needed.update(roots); generated={}
while needed-set(generated):
    key=sorted(needed-set(generated))[0]
    if key in overrides:
        expression=overrides[key]; needed.update(re.findall(r'G\("([A-Z]+[0-9]+)"\)',expression))
    else:
        value=cells.get(key,'')
        expression=Parser(value).expr() if isinstance(value,str) and value.startswith('=') else 'N('+repr(value)+')' if isinstance(value,(int,float)) else 'S('+json.dumps(value)+')'
    generated[key]=expression
code='// Generated by tools/spettri/extract_reference.py from CSLP Spettri-NTC 1.0.3, D1b.\nnamespace GPC.Design.Actions;\n\ninternal sealed partial class Cslp103Grid\n{\n    private V Formula(string cell) => cell switch\n    {\n'
code+='\n'.join('        "'+k+'" => '+v+',' for k,v in sorted(generated.items()))
code+='\n        _ => throw new InvalidOperationException("Cella CSLP non compilata: " + cell)\n    };\n}\n'
(a.output/'Cslp103Grid.Formulas.cs').write_text(code,encoding='utf-8')

# Use the original cached numeric data, not results of the new implementation.
grid=json.loads((a.cached_data/'D1a.json').read_text(encoding='utf-8'))['values'][2:]
xy=json.loads((a.cached_data/'D1b.json').read_text(encoding='utf-8'))['values'][4:]
table=io.StringIO(newline=''); writer=csv.writer(table,lineterminator='\n')
for i,row in enumerate(grid): writer.writerow(row[:3]+xy[i][6:8]+row[3:129])
(a.output/'cslp103-grid.csv.gz').write_bytes(gzip.compress(table.getvalue().encode(),mtime=0))
raw=json.loads((a.cached_data/'D1c.json').read_text(encoding='utf-8'))['values']
regions={int(r[0]):r[1] for r in raw[1:21]}
provinces={int(r[8]):(regions[int(r[7])],r[9]) for r in raw[1:104]}
towns=[]
for row in raw[1:]:
    if not isinstance(row[16],(int,float)) or not row[18]: continue
    region,province=provinces[int(row[16])]
    towns.append([region,province,row[18],row[19],row[20]])
(a.output/'cslp103-towns.json.gz').write_bytes(gzip.compress(json.dumps(towns,ensure_ascii=False).encode(),mtime=0))
print(f'{len(grid)} nodes; {len(towns)} towns; {len(generated)} compiled grid cells')
