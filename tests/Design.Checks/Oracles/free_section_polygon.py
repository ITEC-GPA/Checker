"""Independent section properties of the free concrete sections of ConcreteFreeSectionChecks, not the library code.

Exact rational arithmetic (fractions) on the closed-form polygon integrals (Green's theorem), vertices counterclockwise:
  c_i = x_i y_(i+1) - x_(i+1) y_i,  A = 1/2 sum c_i,
  Sx = 1/6 sum (y_i + y_(i+1)) c_i,  Sy = 1/6 sum (x_i + x_(i+1)) c_i,
  Ixx = 1/12 sum (y_i^2 + y_i y_(i+1) + y_(i+1)^2) c_i   (integral of y^2),
  Iyy = 1/12 sum (x_i^2 + x_i x_(i+1) + x_(i+1)^2) c_i   (integral of x^2),
  Ixy = 1/24 sum (x_i y_(i+1) + 2 x_i y_i + 2 x_(i+1) y_(i+1) + x_(i+1) y_i) c_i   (integral of xy).
Holes are subtracted; the centroidal values follow from the parallel axis theorem: Jxx = Ixx - A yG^2, Jyy = Iyy - A xG^2,
Jxy = Ixy - A xG yG. Hand check of the chamfered trapezoid: trapezoid (800 + 500) / 2 * 600 = 390000 minus the chamfer triangle
(700,0)-(800,0)-(775,100) of area 100 * 100 / 2 = 5000, so A = 385000 mm^2.
Refuses to overwrite the independently calculated expected values.
"""
from fractions import Fraction as F
from pathlib import Path
import json

target = Path(__file__).resolve().parents[1] / 'Fixtures/free-section-independent.json'
if target.exists():
    raise SystemExit('Independent fixture already exists; not overwritten.')


def integrals(points):
    a = sx = sy = ixx = iyy = ixy = F(0)
    for i, (x0, y0) in enumerate(points):
        x1, y1 = points[(i + 1) % len(points)]
        c = x0 * y1 - x1 * y0
        a += c / 2
        sx += (y0 + y1) * c / 6
        sy += (x0 + x1) * c / 6
        ixx += (y0 * y0 + y0 * y1 + y1 * y1) * c / 12
        iyy += (x0 * x0 + x0 * x1 + x1 * x1) * c / 12
        ixy += (x0 * y1 + 2 * x0 * y0 + 2 * x1 * y1 + x1 * y0) * c / 24
    if a < 0:  # clockwise: the same integrals with the opposite sign
        return [-v for v in (a, sx, sy, ixx, iyy, ixy)]
    return [a, sx, sy, ixx, iyy, ixy]


def section(outline, holes):
    total = integrals([(F(x), F(y)) for x, y in outline])
    for hole in holes:
        total = [t - h for t, h in zip(total, integrals([(F(x), F(y)) for x, y in hole]))]
    a, sx, sy, ixx, iyy, ixy = total
    xg, yg = sy / a, sx / a
    values = dict(area=a, xG=xg, yG=yg, Jxx=ixx - a * yg * yg, Jyy=iyy - a * xg * xg, Jxy=ixy - a * xg * yg)
    return dict(outline=outline, holes=holes,
                values={k: float(v) for k, v in values.items()},
                exact={k: f'{v.numerator}/{v.denominator}' for k, v in values.items()})


chamfered = [(0, 0), (700, 0), (775, 100), (650, 600), (150, 600)]
cases = {
    'chamfered-trapezoid': section(chamfered, []),
    'chamfered-trapezoid-with-hole': section(chamfered, [[(300, 200), (400, 400), (500, 200)]]),
}
target.write_text(json.dumps(dict(
    source='Exact polygon integrals (Green), fractions; mm, mm^2, mm^4; centroidal axes parallel to x and y; '
           'Jxy = integral of (x - xG)(y - yG) dA. Generated by Oracles/free_section_polygon.py, independent of the library.',
    cases=cases), indent=2) + '\n', encoding='utf-8')
